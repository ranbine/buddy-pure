#!/usr/bin/env python3
"""gen-agent-evolution.py — auto-aggregate per-agent evolution logs (L2).

Philosophy (2026-10-16): evolution records are a DERIVED artifact, not a
hand-maintained file — same "record is generated, not remembered" idea as
check-drift and the measure/decide split. Sources already exist (git commits,
decisions/, workflow-patterns); this script aggregates them per agent so each
agent gets a single evolution view WITHOUT new manual burden. Re-run anytime;
output is regenerated from source, so it never drifts.

Sources:
  - git log (subject + body) — matched by keyword
  - decisions/*.md           — matched by keyword in filename/first lines
  - .codebuddy/rules/workflow-patterns.md — pattern rows mentioning the agent

Output: contexts/agents-evolution/<agent>.md  (one per real agent)

Usage:
  gen-agent-evolution.py              # regenerate all agents
  gen-agent-evolution.py reviewer     # just one
  gen-agent-evolution.py --dry-run

Convention: commit subjects use <type>(<area>): ... — area often maps to an
agent (reviewer/review -> reviewer). Mapping is keyword-based (name + aliases
+ associated script names), since area != agent 1:1.
"""
import os, re, sys, subprocess

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lib"))
from cbp_paths import P, ROOT, CLI_HOME, setting, local_dict  # noqa: E402
LAB = str(ROOT)
PURE = str(ROOT)
OUT_DIR = str(P["CBP_CONTEXTS"] / "agents-evolution")

# agent -> keywords (lowercased substring match against commit/decision/pattern text)
AGENTS = {
    "reviewer": ["reviewer", "review-artifact", "quality gate", "质量门", "fix(review", "docs(review", "feat(review", "publish-ok", "check_structure", "check_index_sync"],
    "html-generator": ["html-generator", "report-generation", "monthly-review", "daily-report", "monthly review", "daily report", "generate-daily-report", "style-registry", "sync"],
    "health-checker": ["health-checker", "cbp-doctor", "validate-pure", "体检", "校验", "health check"],
    "pure": ["run-agent", "orchestrat", "sub-agent", "subagent", "子 agent", "agent 生态", "welcome", "gen-welcome"],
}
AGENTS.update(local_dict("agent_keywords", list))   # extra agents, config/local.json

def sh(args):
    try:
        return subprocess.check_output(args, cwd=LAB, text=True, stderr=subprocess.DEVNULL)
    except Exception:
        return ""

def git_entries():
    """Return list of (date, subject, body) for all commits (newest first)."""
    raw = sh(["git", "log", "--date=short", "--pretty=format:%x01%ad%x02%s%x02%b%x03"])
    out = []
    for rec in raw.split("\x03"):
        rec = rec.strip().lstrip("\x01")
        if not rec:
            continue
        parts = rec.split("\x02")
        if len(parts) >= 2:
            out.append((parts[0], parts[1], parts[2] if len(parts) > 2 else ""))
    return out

def decision_entries():
    d = os.path.join(PURE, "decisions")
    out = []
    if not os.path.isdir(d):
        return out
    for fn in sorted(os.listdir(d), reverse=True):
        if not fn.endswith(".md") or fn == "README.md":
            continue
        path = os.path.join(d, fn)
        text = open(path, encoding="utf-8", errors="ignore").read()
        m = re.match(r"(\d{4}-\d{2}-\d{2})", fn)
        date = m.group(1) if m else ""
        title = fn[11:-3] if m else fn[:-3]
        out.append((date, title, text, fn))
    return out

def pattern_rows():
    p = os.path.join(PURE, "contexts", "rules", "workflow-patterns.md")
    if not os.path.exists(p):
        return []
    rows = []
    for line in open(p, encoding="utf-8", errors="ignore"):
        if line.startswith("| P-") or re.match(r"\|\s*P-", line):
            rows.append(line.strip())
    return rows

def matches(text, kws):
    t = text.lower()
    return any(k.lower() in t for k in kws)

def build(agent, kws, commits, decisions, patterns):
    lines = [f"# {agent} — evolution log", "",
             "> Auto-generated by `bin/gen-agent-evolution.py` (L2: derived from git",
             "> log + decisions/ + workflow-patterns). Do not hand-edit — re-run the",
             "> script. Source of truth is the commits/decisions themselves.", ""]

    cm = [(d, s, b) for (d, s, b) in commits if matches(s + " " + b, kws)]
    lines.append(f"## Commits ({len(cm)})")
    lines.append("")
    if cm:
        lines.append("| Date | Change |")
        lines.append("|------|--------|")
        for d, s, _b in cm:
            s_esc = s.replace("|", "\\|")
            lines.append(f"| {d} | {s_esc} |")
    else:
        lines.append("_(none matched)_")
    lines.append("")

    dec = [(d, t, fn) for (d, t, txt, fn) in decisions if matches(t + " " + txt, kws)]
    lines.append(f"## Decisions ({len(dec)})")
    lines.append("")
    if dec:
        for d, t, fn in dec:
            lines.append(f"- **{d}** — {t}  (`decisions/{fn}`)")
    else:
        lines.append("_(none matched)_")
    lines.append("")

    pat = [r for r in patterns if matches(r, kws)]
    lines.append(f"## Workflow Patterns ({len(pat)})")
    lines.append("")
    if pat:
        for r in pat:
            cells = [c.strip() for c in r.strip("|").split("|")]
            if len(cells) >= 2:
                lines.append(f"- **{cells[0]}** — {cells[1]}")
    else:
        lines.append("_(none matched)_")
    lines.append("")
    return "\n".join(lines) + "\n"

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry-run" in sys.argv
    targets = args or list(AGENTS)
    commits, decisions, patterns = git_entries(), decision_entries(), pattern_rows()
    os.makedirs(OUT_DIR, exist_ok=True)
    for agent in targets:
        if agent not in AGENTS:
            print(f"unknown agent: {agent} (known: {', '.join(AGENTS)})", file=sys.stderr)
            continue
        md = build(agent, AGENTS[agent], commits, decisions, patterns)
        path = os.path.join(OUT_DIR, f"{agent}.md")
        if dry:
            print(f"--- {path} ---\n{md}")
        else:
            open(path, "w", encoding="utf-8").write(md)
            n = md.count("\n")
            print(f"✅ {path} ({n} lines)")

if __name__ == "__main__":
    main()
